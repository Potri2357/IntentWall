"use client";

import React from "react";
import { FirewallIntentIR, ValidationReport } from "@/lib/api";
import {
  Ban,
  ShieldCheck,
  ShieldAlert,
  Play,
  Wifi,
  Globe,
  TriangleAlert,
  Lock,
  Loader2,
  ArrowRight,
} from "lucide-react";

interface IntentReviewCardProps {
  ir: FirewallIntentIR;
  validation: ValidationReport;
  providerUsed: string;
  onSimulate: () => void;
  isSimulating: boolean;
}

export function IntentReviewCard({
  ir,
  validation,
  providerUsed,
  onSimulate,
  isSimulating,
}: IntentReviewCardProps) {
  const isDenied = ir.action === "deny" || ir.action === "isolate";

  return (
    <div className="bg-[var(--surface-card)] border border-[var(--border)] rounded-2xl p-6 shadow-sm space-y-5 transition-colors">
      {/* Header and Telemetry */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between pb-3.5 border-b border-[var(--border)] gap-3">
        <div className="flex items-center gap-3">
          <div
            className={`w-8 h-8 rounded-lg flex items-center justify-center font-bold uppercase text-xs ${
              ir.action === "deny"
                ? "bg-red-50 dark:bg-red-950/60 text-red-700 dark:text-red-400 border border-red-200 dark:border-red-800"
                : "bg-emerald-50 dark:bg-emerald-950/60 text-emerald-700 dark:text-emerald-400 border border-emerald-200 dark:border-emerald-800"
            }`}
          >
            {isDenied ? <Ban className="w-4 h-4" /> : <ShieldCheck className="w-4 h-4" />}
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h3 className="text-sm font-bold text-[var(--ink-900)]">
                Compiled Intermediate Representation (IR)
              </h3>
              <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-[var(--surface-well)] text-[var(--ink-700)] border border-[var(--border)] font-semibold">
                {ir.intent_id}
              </span>
            </div>
            <p className="text-xs text-[var(--ink-500)] mt-0.5">
              Deterministic semantic graph generated by intent engine ({providerUsed}).
            </p>
          </div>
        </div>

        {/* Lockout Guard Status */}
        <div className="flex items-center gap-2">
          <div
            className={`px-3 py-1.5 rounded-xl text-xs font-mono font-medium border flex items-center gap-2 ${
              validation.lockout_safe
                ? "bg-emerald-50 dark:bg-emerald-950/40 text-emerald-700 dark:text-emerald-400 border-emerald-200 dark:border-emerald-800"
                : "bg-red-50 dark:bg-red-950/40 text-red-700 dark:text-red-400 border-red-200 dark:border-red-800 font-bold"
            }`}
          >
            {validation.lockout_safe ? (
              <>
                <Lock className="w-3.5 h-3.5 text-emerald-600 dark:text-emerald-400" />
                <span>Lockout Guard: Passed</span>
              </>
            ) : (
              <>
                <ShieldAlert className="w-3.5 h-3.5 text-red-600 dark:text-red-400" />
                <span>Lockout Guard: Refused (Port 22 Protected)</span>
              </>
            )}
          </div>
        </div>
      </div>

      {/* Visual Rule Flow Pipeline (Graph) */}
      <div className="p-4 rounded-xl border border-[var(--border)] bg-[var(--surface-well)]">
        <span className="text-[10px] font-mono uppercase tracking-wider text-[var(--ink-500)] font-bold block mb-3">
          Packet Evaluation Flow
        </span>

        <div className="flex flex-col md:flex-row items-center justify-between gap-3 text-xs font-mono">
          {/* Source Box */}
          <div className="w-full md:w-auto flex-1 p-3 rounded-lg bg-[var(--surface-card)] border border-[var(--border)] shadow-xs">
            <div className="flex items-center gap-1.5 text-[var(--ink-500)] text-[10px] mb-1">
              <Wifi className="w-3 h-3" />
              <span>SOURCE INGRESS</span>
            </div>
            <span className="text-xs font-bold text-[var(--ink-900)] block truncate">
              {ir.source.ref} ({ir.source.type})
            </span>
            <span className="text-[10px] text-[var(--ink-400)] block">{ir.source.cidr || "Any Host"}</span>
          </div>

          <ArrowRight className="w-4 h-4 text-[var(--ink-400)] shrink-0 hidden md:block" />

          {/* Action / Verdict Box */}
          <div className="w-full md:w-auto p-3 rounded-lg border text-center shadow-xs min-w-[130px] bg-[var(--surface-card)] border-[var(--border)]">
            <span className="text-[10px] text-[var(--ink-500)] block mb-0.5">NETFILTER HOOK</span>
            <span
              className={`font-bold uppercase text-xs px-2 py-0.5 rounded inline-block ${
                isDenied
                  ? "bg-red-100 dark:bg-red-950/60 text-red-700 dark:text-red-400"
                  : "bg-emerald-100 dark:bg-emerald-950/60 text-emerald-700 dark:text-emerald-400"
              }`}
            >
              {ir.action}
            </span>
            <span className="text-[10px] text-[var(--ink-400)] block mt-1">{ir.direction.toUpperCase()}</span>
          </div>

          <ArrowRight className="w-4 h-4 text-[var(--ink-400)] shrink-0 hidden md:block" />

          {/* Destination Box */}
          <div className="w-full md:w-auto flex-1 p-3 rounded-lg bg-[var(--surface-card)] border border-[var(--border)] shadow-xs">
            <div className="flex items-center gap-1.5 text-[var(--ink-500)] text-[10px] mb-1">
              <Globe className="w-3 h-3" />
              <span>DESTINATION EGRESS</span>
            </div>
            <span className="text-xs font-bold text-[var(--ink-900)] block truncate">
              {ir.destination.ref} ({ir.destination.type})
            </span>
            <span className="text-[10px] text-[var(--ink-400)] block">
              {ir.protocols?.map((p) => `${(p.proto || "TCP").toUpperCase()}/${p.port || "ANY"}`).join(", ") || "All Protocols"}
            </span>
          </div>
        </div>
      </div>

      {/* Explanation & Telemetry Bar */}
      <div className="grid grid-cols-1 md:grid-cols-4 gap-3 text-xs">
        <div className="md:col-span-3 p-3.5 rounded-xl border border-[var(--border)] bg-[var(--surface-well)]">
          <span className="text-[10px] font-mono uppercase tracking-wider text-[var(--ink-500)] block mb-1">
            Compiler Natural Language Rationale
          </span>
          <p className="text-[var(--ink-700)] font-mono text-[11px] leading-relaxed">
            {ir.explanation}
          </p>
        </div>

        <div className="p-3.5 rounded-xl border border-[var(--border)] bg-[var(--surface-well)] flex flex-col justify-between font-mono text-[11px]">
          <div>
            <span className="text-[var(--ink-500)] block text-[10px]">PARSER CONFIDENCE</span>
            <span className="text-sm font-bold text-[var(--ink-900)]">
              {Math.round(ir.confidence * 100)}%
            </span>
          </div>
          <div className="pt-2 border-t border-[var(--border)] text-[var(--ink-400)] text-[10px]">
            Blast Radius: ~{validation.blast_radius?.estimated_hosts || 20} Hosts
          </div>
        </div>
      </div>

      {/* Adversarial Alerts */}
      {validation.issues.length > 0 && (
        <div className="space-y-2">
          {validation.issues.map((iss, idx) => (
            <div
              key={idx}
              className={`p-3 rounded-xl text-xs flex items-start gap-2.5 border ${
                iss.severity === "critical"
                  ? "bg-red-50/70 dark:bg-red-950/40 text-red-800 dark:text-red-300 border-red-200 dark:border-red-800"
                  : "bg-amber-50/70 dark:bg-amber-950/40 text-amber-800 dark:text-amber-300 border-amber-200 dark:border-amber-800"
              }`}
            >
              <TriangleAlert className="w-4 h-4 shrink-0 mt-0.5" />
              <div>
                <span className="font-bold font-mono">[{iss.code}]:</span> {iss.message}
                {iss.suggested_fix && (
                  <span className="block mt-1 font-mono text-[11px] opacity-90">
                    Fix Recommendation: {iss.suggested_fix}
                  </span>
                )}
              </div>
            </div>
          ))}
        </div>
      )}

      {/* Action Footer */}
      <div className="pt-3 border-t border-[var(--border)] flex items-center justify-between">
        <span className="text-xs font-mono text-[var(--ink-500)]">
          Synthesized Linux nftables rules ready for verification probe suite.
        </span>

        <button
          onClick={onSimulate}
          disabled={isSimulating || !validation.lockout_safe}
          aria-label="Simulate policy in sandbox"
          className="px-5 py-2.5 rounded-xl text-xs font-bold flex items-center gap-2 bg-[var(--ink-900)] text-[var(--bg)] hover:opacity-90 transition-all cursor-pointer disabled:opacity-50 shadow-xs"
        >
          {isSimulating ? (
            <>
              <Loader2 className="w-3.5 h-3.5 animate-spin" />
              <span>Simulating Probes...</span>
            </>
          ) : (
            <>
              <Play className="w-3.5 h-3.5" />
              <span>Execute Sandbox Verification</span>
            </>
          )}
        </button>
      </div>
    </div>
  );
}
